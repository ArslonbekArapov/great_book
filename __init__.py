# arslonbek_tools - a simple Python library by Arslonbek

def greet(name):
    """Say hello to someone"""
    return f"Hello, {name}! Nice to meet you :)"

def add(a, b):
    """Add two numbers"""
    return a + b

def is_even(n):
    """Check if a number is even"""
    return n % 2 == 0

def reverse_text(text):
    """Reverse a string"""
    return text[::-1]

def celsius_to_fahrenheit(c):
    """Convert Celsius to Fahrenheit"""
    return (c * 9/5) + 32
